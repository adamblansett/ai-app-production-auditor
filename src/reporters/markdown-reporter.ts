import type { AuditReport } from '../models/report.js';
import type { Finding, Severity } from '../models/finding.js';

export function formatMarkdownReport(report: AuditReport): string {
  const lines: string[] = [];

  lines.push('# Production Readiness Audit Report');
  lines.push('');
  lines.push(
    `Generated by **${report.tool.name}** (v${report.tool.version}) on ${report.scan.timestamp}.`,
  );
  lines.push('');

  // Project Information
  lines.push('## Project Information');
  lines.push('');
  lines.push(`- **Project Name:** ${report.project.name}`);
  if (report.project.version) {
    lines.push(`- **Version:** ${report.project.version}`);
  }
  lines.push(`- **Project Type:** ${report.project.type}`);
  lines.push(`- **Frameworks:** ${report.project.frameworks.join(', ') || 'None detected'}`);
  lines.push(`- **Tools & Libraries:** ${report.project.tools.join(', ') || 'None detected'}`);
  lines.push(
    `- **Monorepo:** ${report.project.isMonorepo ? `Yes (${report.project.packageCount} packages)` : 'No'}`,
  );
  lines.push(`- **Target Directory:** \`${report.scan.targetDirectory}\``);
  lines.push('');

  // Summary Table
  lines.push('## Audit Summary');
  lines.push('');
  lines.push('| Metric | Count |');
  lines.push('| :--- | :--- |');
  lines.push(`| **Total Findings** | **${report.summary.totalFindings}** |`);
  lines.push(`| Critical | ${report.summary.critical} |`);
  lines.push(`| High | ${report.summary.high} |`);
  lines.push(`| Medium | ${report.summary.medium} |`);
  lines.push(`| Low | ${report.summary.low} |`);
  lines.push(`| Info | ${report.summary.info} |`);
  lines.push(`| Checks Completed | ${report.summary.passedChecks} |`);
  lines.push(`| Checks Skipped | ${report.summary.skippedChecks} |`);
  lines.push(`| Files Scanned | ${report.summary.filesScanned} |`);
  lines.push(`| Scan Duration | ${report.summary.durationMs}ms |`);
  lines.push('');

  // Detailed Findings
  lines.push('## Findings');
  lines.push('');

  if (report.findings.length === 0) {
    lines.push('> [!NOTE]');
    lines.push('> No production-readiness issues were identified during this audit.');
    lines.push('');
  } else {
    const severityOrder: Severity[] = ['critical', 'high', 'medium', 'low', 'info'];

    for (const sev of severityOrder) {
      const matching = report.findings.filter((f) => f.severity === sev);
      if (matching.length === 0) continue;

      lines.push(`### ${sev.toUpperCase()} Severity (${matching.length})`);
      lines.push('');

      for (const finding of matching) {
        lines.push(formatMarkdownFinding(finding));
      }
    }
  }

  // Checks and Limitations
  lines.push('## Audit Coverage & Limitations');
  lines.push('');
  lines.push('### Diagnostic Checks');
  lines.push('');
  lines.push('| Check ID | Name | Status | Details |');
  lines.push('| :--- | :--- | :--- | :--- |');
  for (const check of report.checks) {
    const details = check.skippedReason ? check.skippedReason : 'Executed';
    lines.push(`| \`${check.id}\` | ${check.name} | **${check.status}** | ${details} |`);
  }
  lines.push('');

  if (report.skippedFiles.length > 0) {
    lines.push('### Skipped Files');
    lines.push('');
    lines.push(
      `A total of ${report.skippedFiles.length} file(s) were excluded from deep content analysis.`,
    );
    lines.push('');
    lines.push('<details><summary>View skipped files list</summary>');
    lines.push('');
    lines.push('| Path | Reason |');
    lines.push('| :--- | :--- |');
    for (const file of report.skippedFiles.slice(0, 50)) {
      lines.push(`| \`${file.path}\` | ${file.reason} |`);
    }
    if (report.skippedFiles.length > 50) {
      lines.push(`| ... | (${report.skippedFiles.length - 50} additional files omitted) |`);
    }
    lines.push('');
    lines.push('</details>');
    lines.push('');
  }

  lines.push('---');
  lines.push(
    `*Report generated by [ai-app-production-auditor](${report.tool.homepage}) by ${report.tool.author}.*`,
  );
  lines.push('');

  return lines.join('\n');
}

function formatMarkdownFinding(finding: Finding): string {
  const lines: string[] = [];
  const loc = finding.file
    ? `\`${finding.file}${finding.line ? `:${finding.line}` : ''}${finding.column ? `:${finding.column}` : ''}\``
    : '*Project root*';

  lines.push(`#### [${finding.ruleId}] ${finding.title}`);
  lines.push('');
  lines.push(`- **Location:** ${loc}`);
  lines.push(`- **Confidence:** ${finding.confidence}`);
  lines.push(`- **Description:** ${finding.message}`);
  lines.push('');

  if (finding.evidence) {
    lines.push('**Evidence:**');
    lines.push('```');
    lines.push(finding.evidence);
    lines.push('```');
    lines.push('');
  }

  lines.push(`**Remediation:** ${finding.remediation}`);
  lines.push('');

  return lines.join('\n');
}
